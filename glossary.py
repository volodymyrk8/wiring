def tip_for(item: dict) -> str:
    # Short hover tip: prefer the chip hint; caption still uses expand + blurb.
    hint = (item.get("hint") or "").strip()
    if hint:
        return hint
    extra = GLOSS.get(item["id"], {})
    return (extra.get("expand") or "").strip()


def enrich(items: list[dict]) -> list[dict]:
    out = []
    for item in items:
        extra = GLOSS.get(item["id"], {})
        out.append({**item, "expand": extra.get("expand") or "", "blurb": extra.get("blurb") or item.get("hint") or "", "tip": tip_for(item)})
    return out


def glossary_html() -> str:
    blocks = [
        "<p>Буквы и слова с анкет — простым языком. С шуткой, но по делу. "
        "Это не диагноз и не учебник. Врача мы не заменяем. Самодиагностика на WIRING нормальная.</p>",
        "<p>Нажми на тег в ленте — выскочит коротко. Здесь то же самое, только можно спокойно дочитать.</p>",
    ]
    for title, items in (("буквы на анкете", NEURO), ("как со мной можно", VIBE)):
        blocks.append(f"<h2>{escape(title)}</h2>")
        for item in enrich(items):
            blocks.append(
                "<article class=\"abbr\" id=\""
                + escape(item["id"])
                + "\">"
                + "<h3>"
                + escape(item["label"])
                + "</h3>"
                + ("<p class=\"expand\">" + escape(item["expand"]) + "</p>" if item["expand"] else "")
                + "<p>"
                + escape(item["blurb"])
                + "</p></article>"
            )
    return "\n".join(blocks)
